TEST(LeptonTest, TestInvalidPacket) {
    const std::vector<uint8_t> InvalidPacket = {0x5f,0xff,0xff,0xff,0x00};
    const auto header = VoISP::packet_id(InvalidPacket.data());
    const bool isDiscardPacket = VoISP::is_discard_packet(header);
    EXPECT_TRUE(isDiscardPacket);
}

TEST(LeptonTest, TestValidPacket) {
    const auto header = VoISP::packet_id(ValidPacket.data());
    const bool isDiscardPacket = VoISP::is_discard_packet(header);
    EXPECT_FALSE(isDiscardPacket);
}

TEST(LeptonTest, TextCRC1) {
    const auto crcA = VoISP::packet_crc(ValidPacket.data());
    const auto crcC = VoISP::computeCRC(ValidPacket.data(), ValidPacket.size());
    EXPECT_EQ(crcA, crcC);
}

